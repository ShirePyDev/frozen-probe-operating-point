"""The IV-B config-deltas table (the author's item 5 of 2026-10-16g, D-472 (5)): one row per update pair.

    python src/config_table_d472.py           # writes paper/tables_config.tex (the file paper/main.tex \\inputs)
    python src/config_table_d472.py --print   # also prints each row's text

A new module (F-092). Every entry is COPIED from the committed record docs/paper/config_deltas_d471.json (D-471,
registered in D-470): nothing is computed but the short forms below. The header names the record with its sha256,
so src/check_paper.py's 'generated' step (D-438) can rebuild the file and compare it byte for byte.

ROWS. For each of the record's 18 pairs (1a-1h, 2a-2j; the IDs of src/pairs_table_d468.py, D-468 (4)): the
registered fields (D-470) whose value differs, as 'field pre -> post', in the record's field order; 'none' when no
field differs; 'not found (gated)' when a side's config.json was not read (the record's deltas are 'NOT FOUND'); the
caption explains 'Not found' only when a row has it (D-558 (4c), D-561 (4): since D-561 every pair is read). A
rope_scaling change of the same type names the keys that differ. Pairs with the same text share one table row (the
page budget, D-472 (5)); the rows are in the order of their first ID, and every pair is in exactly one row.

SHORT FORMS. rope_theta as m x 10^e; integers as written; null as 'none'; adjacent math groups are merged (a '$$'
would open display math).
"""
from __future__ import annotations

import hashlib
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REC = "docs/paper/config_deltas_d471.json"
PAPER_DIR = ROOT / os.environ.get("GUARDRAIL_PAPER_DIR", "paper")  # where the .tex files are written (README, config/example.env)
OUT = PAPER_DIR / "tables_config.tex"
LABEL = {"rope_theta": "RoPE base", "rope_scaling": "RoPE scaling", "sliding_window": "sliding window",
         "max_position_embeddings": "max positions", "hidden_size": "hidden size", "num_hidden_layers": "layers",
         "vocab_size": "vocabulary"}
NOT_FOUND = "not found (gated)"


def sci(x) -> str:
    m, e = f"{float(x):.0e}".split("e")
    if float(f"{m}e{e}") != float(x):
        return str(x)
    e = int(e)
    return f"$10^{{{e}}}$" if m == "1" else f"${m}\\cdot10^{{{e}}}$"


def val(field: str, v) -> str:
    if v is None:
        return "none"
    if field == "rope_theta":
        return sci(v)
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return str(v)


def change(field: str, d: dict) -> str:
    name = LABEL[field]
    if field == "rope_scaling":
        a, b = d["pre"], d["post"]
        if d["type_pre"] == d["type_post"] and isinstance(a, dict) and isinstance(b, dict):
            keys = sorted(k for k in set(a) | set(b) if a.get(k) != b.get(k))
            return f"{name} {d['type_pre']}, " + " and ".join(k.replace("_", r"\_") for k in keys) + " changed"
        return f"{name} {d['type_pre']}$\\to${d['type_post']}"
    if field == "sliding_window" and d["pre"] == d["post"]:
        return f"{name} use flag {d['use_sliding_window_pre']}$\\to${d['use_sliding_window_post']}"
    return f"{name} {val(field, d['pre'])}$\\to${val(field, d['post'])}".replace("$$", "")   # one math group


def rows(rec: dict) -> list[tuple[int, str, str]]:
    order = rec["fields"]
    out = []
    for p in rec["pairs"]:
        dl = p["deltas"]
        if dl == "NOT FOUND":
            text = NOT_FOUND
        elif not dl:
            text = "none"
        else:
            text = "; ".join(change(f, dl[f]) for f in order if f in dl)
        out.append((p["phase"], p["id"], text))
    ids = [i for _, i, _ in out]
    if len(ids) != 18 or len(set(ids)) != 18:
        raise SystemExit(f"{REC}: expected 18 distinct pairs, got {ids}")
    return out


def ids_text(ids: list[str]) -> str:
    """'1a, 1f, 2c, 2e--2i': runs of three or more consecutive IDs of one phase joined by an en dash."""
    out, run = [], [ids[0]]
    for a in ids[1:]:
        b = run[-1]
        if a[0] == b[0] and ord(a[1]) == ord(b[1]) + 1:
            run.append(a)
        else:
            out.append(run)
            run = [a]
    out.append(run)
    return ", ".join(f"{r[0]}--{r[-1]}" if len(r) >= 3 else ", ".join(r) for r in out)


def groups(rs: list[tuple[int, str, str]]) -> list[tuple[list[str], str]]:
    by: dict[str, list[str]] = {}
    for _, i, t in rs:
        by.setdefault(t, []).append(i)
    return sorted(((ids, t) for t, ids in by.items()), key=lambda g: g[0][0])


def tex(rs: list[tuple[int, str, str]], sha: str) -> str:
    nf = any(t == NOT_FOUND for _, _, t in rs)
    lines = ["% GENERATED by src/config_table_d472.py (D-472 (5)): do not edit; rerun the script.",
             f"% Source (sha256): {REC} {sha}",
             r"\begin{table}[t]",
             r"\caption{Configuration changes of the update pairs: the fields of config.json, at the pinned "
             r"revisions, that differ from the pre- to the post-update checkpoint, among the RoPE base, RoPE scaling, "
             r"sliding window, maximum positions, hidden size, layer count and vocabulary size."
             + (r" Not found: a gated checkpoint whose file we did not read." if nf else "") + "}",
             r"\label{tab:config}",
             r"\centering\footnotesize",
             r"\begin{tabular}{@{}p{0.26\columnwidth}p{0.68\columnwidth}@{}}",
             r"\toprule",
             r"Pairs & Fields that change (pre$\to$post) \\",
             r"\midrule"]
    lines += [f"{ids_text(ids)} & {t} \\\\" for ids, t in groups(rs)]
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    b = (ROOT / REC).read_bytes()
    rs = rows(json.loads(b.decode("utf-8")))
    OUT.write_bytes(tex(rs, hashlib.sha256(b).hexdigest()).encode("utf-8"))
    if "--print" in argv:
        for _, i, t in rs:
            print(i, t)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
